"""Frozen payload contracts.

Interface breakage in agent systems is data-shape drift, not signature drift. These
dataclasses are the real interface between layers and carry a declared version.

Compatibility rule, within a major version:
    fields may be ADDED with a default; they are never removed, renamed, or retyped.

External components depend on this. Do not edit this file in a feature PR - open an issue.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

PAYLOAD_VERSION = "1.1"  # 1.1: TaskSpec.document_tokens added, with a default


@dataclass(frozen=True)
class Observation:
    """One result of one action, as seen by the agent. Errors are observations, not exceptions."""

    step: int
    content: str
    tool_name: str | None = None
    error: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class MemoryQuery:
    """Deliberately wide.

    A narrow retrieve(text, k) suits vector memory and handicaps graph memory, which needs
    entity anchors and hop depth, and episodic memory, which needs time windows. Narrowing
    it would force those implementations to smuggle structure through a string, and we
    would be benchmarking crippled versions of them.

    Implementations ignore fields they do not support. They must not crash on them.
    """

    text: str | None = None
    k: int = 5
    time_range: tuple[int, int] | None = None
    entities: list[str] | None = None
    hops: int = 1
    filters: dict[str, Any] | None = None


@dataclass(frozen=True)
class MemoryItem:
    content: str
    score: float
    provenance: str  # originating run id + step
    kind: str  # episodic | semantic | procedural | failure


@dataclass(frozen=True)
class Action:
    tool_name: str
    arguments: dict[str, Any]
    rationale: str | None = None


@dataclass(frozen=True)
class ContextWindow:
    """`dropped` is load-bearing.

    Without a record of what the budget evicted, an Experiment 2 result cannot distinguish
    "memory failed to recover the fact" from "the fact was never evicted in the first
    place". Record segment identifiers and reasons here, never secret payloads.
    """

    segments: list[tuple[str, str]]  # (role, text)
    token_count: int
    dropped: list[str]


@dataclass(frozen=True)
class Verdict:
    success: bool
    score: float
    per_step: list[bool]
    reason: str


@dataclass(frozen=True)
class TaskSpec:
    """One source of truth. The generator emits the task, its checker and its per-step gold
    labels from this, which is what makes OracleMemory and retrieval precision/recall
    possible at all."""

    task_id: str
    family: str  # multihop_qa | mock_fs | repo_edit
    fact_dependency_graph: dict[str, list[str]]
    recall_distance: int
    distractor_density: float
    horizon: int
    entity_pool: list[str]
    seed: int
    #: Approximate length every document is padded to. 0 = one sentence per document.
    document_tokens: int = 0


@dataclass(frozen=True)
class TraceEvent:
    """Every layer emits these. Nobody logs directly."""

    run_id: str
    step: int
    layer: str  # planner | context | memory | tools | evaluator | runtime
    kind: str  # action | observation | retrieval | eviction | verdict | error
    payload: dict[str, Any]
    token_counts: dict[str, int] = field(default_factory=dict)
    wall_ms: float = 0.0


@dataclass(frozen=True)
class RunProvenance:
    """A result whose provenance cannot be reconstructed is not a result."""

    run_id: str
    config_hash: str
    git_commit: str
    payload_version: str
    model_id: str
    model_revision: str
    embedding_model: str
    embedding_revision: str
    seeds: dict[str, int]
